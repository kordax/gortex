func TestCensusAdmissionPreservesManifestShebangNegationsAndFrontier(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"main.go":           "package fixture\nfunc Main() {}\n",
		"go.mod":            "module example.invalid/fixture\ngo 1.27\n",
		"script":            "#!/bin/bash\necho fixture\n",
		"generated/keep.go": "package fixture\nfunc Keep() {}\n",
		"generated/drop.go": "package fixture\nfunc Drop() {}\n",
		"main_test.go":      "package fixture\nfunc TestFixture() {}\n",
		"sub/visible.go":    "package fixture\nfunc Visible() {}\n",
		"sub/hidden.go":     "package fixture\nfunc Hidden() {}\n",
		"sub/.gortexignore": "hidden.go\n",
		"ignored.blob":      "opaque generated bytes\n",
	}
	mtimes := make(map[string]int64)
	for rel, body := range files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o700))
		require.NoError(t, os.WriteFile(path, []byte(body), 0o600))
		info, err := os.Stat(path)
		require.NoError(t, err)
		if rel != "sub/.gortexignore" {
			mtimes[rel] = info.ModTime().UnixNano()
		}
	}
	mtimes["deleted.go"] = 1
	registry := newTestRegistry()
	registry.Register(languages.NewBashExtractor())
	idx := New(graph.New(), registry, config.IndexConfig{Exclude: []string{
		"generated/", "!generated/keep.go", "**/*_test.go", "**/*.blob",
	}}, zap.NewNop())
	t.Cleanup(idx.Close)
	idx.SetFileMtimes(mtimes)
	changed, deleted, detected, err := idx.changedSinceMtimesCensus(root)
	require.NoError(t, err)
	assert.Empty(t, changed)
	assert.ElementsMatch(t, []string{"deleted.go", "generated/drop.go", "main_test.go", "sub/hidden.go", "ignored.blob"}, deleted)
	assert.Equal(t, 5, detected, "root manifest and extensionless shebang remain in the census")
	assert.True(t, idx.HasChangesSinceMtimes(root), "missing tracked file remains stale")

	for _, rel := range deleted {
		delete(mtimes, rel)
	}
	idx.SetFileMtimes(mtimes)
	assert.False(t, idx.HasChangesSinceMtimes(root), "ignored files and negated descendant must agree with the census")
	require.NoError(t, os.Chtimes(filepath.Join(root, "main.go"), time.Now(), time.Now().Add(time.Second)))
	require.NoError(t, os.Remove(filepath.Join(root, "sub", "visible.go")))
	changed, deleted, detected, err = idx.changedSinceMtimesCensus(root)
	require.NoError(t, err)
	assert.Equal(t, []string{"main.go"}, changed)
	assert.Equal(t, []string{"sub/visible.go"}, deleted)
	assert.Equal(t, 4, detected)
	assert.True(t, idx.HasChangesSinceMtimes(root))
}

func TestCensusAdmissionMissingRootIsConservative(t *testing.T) {
	root := filepath.Join(t.TempDir(), "missing-checkout")
	idx := New(graph.New(), newTestRegistry(), config.IndexConfig{}, zap.NewNop())
	t.Cleanup(idx.Close)
	assert.True(t, idx.HasChangesSinceMtimes(root), "a failed walk cannot certify an unchanged checkout")
	changed, deleted, detected, err := idx.changedSinceMtimesCensus(root)
	require.ErrorIs(t, err, os.ErrNotExist)
	assert.Nil(t, changed)
	assert.Nil(t, deleted)
	assert.Zero(t, detected)
}

func TestCensusAdmissionStillFollowsConfinedSourceSymlinks(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "main.go")
	require.NoError(t, os.WriteFile(path, []byte("package fixture\nfunc Main() {}\n"), 0o600))
	if err := os.Symlink("main.go", filepath.Join(root, "alias.go")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	outside := filepath.Join(t.TempDir(), "outside.go")
	require.NoError(t, os.WriteFile(outside, []byte("package outside\nfunc Secret() {}\n"), 0o600))
	require.NoError(t, os.Symlink(outside, filepath.Join(root, "escape.go")))
	info, err := os.Stat(path)
	require.NoError(t, err)
	idx := New(graph.New(), newTestRegistry(), config.IndexConfig{}, zap.NewNop())
	t.Cleanup(idx.Close)
	idx.SetFileMtimes(map[string]int64{"main.go": info.ModTime().UnixNano(), "alias.go": info.ModTime().UnixNano()})
	changed, deleted, detected, err := idx.changedSinceMtimesCensus(root)
	require.NoError(t, err)
	assert.Empty(t, changed)
	assert.Empty(t, deleted)
	assert.Equal(t, 2, detected)
	assert.False(t, idx.HasChangesSinceMtimes(root))
	require.NoError(t, os.Chtimes(path, time.Now(), time.Now().Add(time.Second)))
	changed, _, detected, err = idx.changedSinceMtimesCensus(root)
	require.NoError(t, err)
	assert.ElementsMatch(t, []string{"main.go", "alias.go"}, changed)
	assert.Equal(t, 2, detected)
	assert.True(t, idx.HasChangesSinceMtimes(root))
}
